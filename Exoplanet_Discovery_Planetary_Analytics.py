"""## 6. Outlier detection and binning

The IQR method below flags potential outliers in planetary radius and orbital period. Treat the results as review flags, not automatic deletions. Binning is used to summarize distributions; bin labels are analysis choices and should be documented.

"""

def iqr_outlier_summary(series):
    values = series.dropna()
    if values.empty:
        return {"Q1": np.nan, "Q3": np.nan, "IQR": np.nan, "lower_bound": np.nan, "upper_bound": np.nan, "outlier_count": 0}
    q1 = values.quantile(0.25)
    q3 = values.quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    count = int(((values < lower) | (values > upper)).sum())
    return {"Q1": q1, "Q3": q3, "IQR": iqr, "lower_bound": lower, "upper_bound": upper, "outlier_count": count}

outlier_report = pd.DataFrame({
    col: iqr_outlier_summary(clean_df[col])
    for col in ["pl_rade", "pl_orbper", "pl_bmasse"]
}).T
display(outlier_report)

